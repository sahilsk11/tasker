import assert from "node:assert/strict";
import { appendFile, mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { SESSION_MESSAGE_MAX_TEXT_LENGTH, sessionMessageSchema } from "@tasker/core";
import { locateClaudeTranscript, readClaudeTranscript } from "./claude.js";

function toJsonl(records: readonly unknown[]): string {
  return `${records.map((record) => JSON.stringify(record)).join("\n")}\n`;
}

void test("readClaudeTranscript filters noise, handles multi-block assistant records, truncates, and keeps stable externalIds", async () => {
  const dir = await mkdtemp(join(tmpdir(), "tasker-claude-test-"));
  const filePath = join(dir, "session-abc.jsonl");

  try {
    const hugeText = `BEGIN-${"z".repeat(SESSION_MESSAGE_MAX_TEXT_LENGTH + 1_234)}-END`;
    const initialRecords = [
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: "<system-reminder>injected system note</system-reminder>",
          role: "user"
        },
        timestamp: "2026-11-23T10:00:00.000Z",
        type: "user",
        uuid: "u-only-reminder"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: "<local-command-caveat>skip me</local-command-caveat>",
          role: "user"
        },
        timestamp: "2026-11-23T10:00:01.000Z",
        type: "user",
        uuid: "u-local-cmd"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: "<command-name>/clear</command-name>",
          role: "user"
        },
        timestamp: "2026-11-23T10:00:02.000Z",
        type: "user",
        uuid: "u-cmd-name"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: "Caveat: The messages below were generated by the user while running local commands.",
          role: "user"
        },
        timestamp: "2026-11-23T10:00:03.000Z",
        type: "user",
        uuid: "u-caveat"
      },
      {
        isMeta: true,
        isSidechain: false,
        message: {
          content: "Meta message should be dropped",
          role: "user"
        },
        timestamp: "2026-11-23T10:00:04.000Z",
        type: "user",
        uuid: "u-meta"
      },
      {
        isMeta: false,
        isSidechain: true,
        message: {
          content: "Sidechain prompt should be dropped",
          role: "user"
        },
        timestamp: "2026-11-23T10:00:05.000Z",
        type: "user",
        uuid: "u-sidechain"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: "<system-reminder>hidden block</system-reminder>\nShip the extractor",
          role: "user"
        },
        timestamp: "2026-11-23T10:01:00.000Z",
        type: "user",
        uuid: "u-1"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: [
            { thinking: "internal reasoning", type: "thinking" },
            { text: "First assistant paragraph", type: "text" },
            { id: "tool_1", input: { command: "ls" }, name: "Bash", type: "tool_use" },
            { text: "   ", type: "text" },
            { text: "Second assistant paragraph", type: "text" }
          ],
          role: "assistant"
        },
        timestamp: "2026-11-23T10:01:05.500Z",
        type: "assistant",
        uuid: "a-multi"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: [
            { content: "file1.ts", tool_use_id: "tool_1", type: "tool_result" },
            { text: "ignored alongside tool_result", type: "text" }
          ],
          role: "user"
        },
        timestamp: "2026-11-23T10:01:06.000Z",
        type: "user",
        uuid: "u-tool-result"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: [{ text: hugeText, type: "text" }],
          role: "assistant"
        },
        type: "assistant",
        uuid: "a-huge"
      }
    ];

    await writeFile(filePath, `${toJsonl(initialRecords)}not-valid-json\n`, "utf8");

    const firstRead = await readClaudeTranscript(filePath);
    assert.equal(firstRead.length, 4);

    for (const msg of firstRead) {
      assert.doesNotThrow(() => sessionMessageSchema.parse(msg));
    }

    assert.deepEqual(firstRead[0], {
      externalId: "u-1",
      occurredAt: "2026-11-23T10:01:00.000Z",
      ordinal: 0,
      role: "user",
      text: "Ship the extractor"
    });
    assert.deepEqual(firstRead[1], {
      externalId: "a-multi:0",
      occurredAt: "2026-11-23T10:01:05.500Z",
      ordinal: 1,
      role: "assistant",
      text: "First assistant paragraph"
    });
    assert.deepEqual(firstRead[2], {
      externalId: "a-multi:1",
      occurredAt: "2026-11-23T10:01:05.500Z",
      ordinal: 2,
      role: "assistant",
      text: "Second assistant paragraph"
    });

    const hugeMessage = firstRead[3];
    assert.ok(hugeMessage != null);
    assert.equal(hugeMessage.externalId, "a-huge");
    assert.equal(hugeMessage.ordinal, 3);
    assert.equal(hugeMessage.role, "assistant");
    assert.equal(hugeMessage.occurredAt, null);
    assert.ok(hugeMessage.text.length <= SESSION_MESSAGE_MAX_TEXT_LENGTH);
    assert.match(hugeMessage.text, /^BEGIN-z+…\[truncated \d+ chars\]$/u);

    // Append new records and verify earlier externalIds and ordinals are completely stable.
    const appendedRecords = [
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: [
            { text: "Line one", type: "text" },
            { text: "Line two", type: "text" }
          ],
          role: "user"
        },
        timestamp: "2026-11-23T10:02:00.000Z",
        type: "user",
        uuid: "u-2"
      },
      {
        isMeta: false,
        isSidechain: false,
        message: {
          content: [{ text: "All done!", type: "text" }],
          role: "assistant"
        },
        timestamp: "2026-11-23T10:02:02.000Z",
        type: "assistant",
        uuid: "a-final"
      }
    ];

    await appendFile(filePath, toJsonl(appendedRecords), "utf8");
    const secondRead = await readClaudeTranscript(filePath);

    assert.equal(secondRead.length, 6);
    assert.deepEqual(secondRead.slice(0, 4), firstRead);
    assert.deepEqual(secondRead[4], {
      externalId: "u-2",
      occurredAt: "2026-11-23T10:02:00.000Z",
      ordinal: 4,
      role: "user",
      text: "Line one\nLine two"
    });
    assert.deepEqual(secondRead[5], {
      externalId: "a-final",
      occurredAt: "2026-11-23T10:02:02.000Z",
      ordinal: 5,
      role: "assistant",
      text: "All done!"
    });
  } finally {
    await rm(dir, { force: true, recursive: true });
  }
});

void test("locateClaudeTranscript finds a session under injectable homeDir and guards invalid IDs", async () => {
  const homeDir = await mkdtemp(join(tmpdir(), "tasker-claude-home-"));

  try {
    const projectDir = join(homeDir, ".claude", "projects", "-Users-dev-repo");
    await mkdir(projectDir, { recursive: true });
    const targetPath = join(projectDir, "thread-123.jsonl");
    await writeFile(targetPath, "{}\n", "utf8");

    assert.equal(
      await locateClaudeTranscript("thread-123", { homeDir }),
      targetPath
    );
    assert.equal(
      await locateClaudeTranscript("missing-thread", { homeDir }),
      null
    );
    assert.equal(
      await locateClaudeTranscript("../escape", { homeDir }),
      null
    );
  } finally {
    await rm(homeDir, { force: true, recursive: true });
  }
});
